#!/usr/bin/env node
'use strict';

/**
 * Build bundled React TSX components for icon sets.
 *
 * Usage:
 *   node scripts/build_react_icons.js               # all sets
 *   node scripts/build_react_icons.js vscode auth0  # specific sets
 *
 * For each set this script:
 *   1. Reads every SVG from sets/<set>/<icon>.svg
 *   2. Converts it to a TSX React component via svg_to_tsx.js
 *   3. Writes src/react/<set>/<icon>.tsx
 *   4. Writes a barrel src/react/<set>/index.ts re-exporting all icons
 */

const fs = require('fs');
const path = require('path');
const {svgToTsx, toComponentName} = require('./svg_to_tsx');

const ROOT = path.resolve(__dirname, '..');
const SETS_DIR = path.join(ROOT, 'sets');
const OUT_DIR = path.join(ROOT, 'src', 'react');

const allSets = require(path.join(SETS_DIR, 'index.json'));

// Determine which sets to process (CLI args or all)
const requestedSets = process.argv.slice(2);
const setsToProcess = requestedSets.length > 0 ? requestedSets : allSets;

for (const set of setsToProcess) {
  if (!allSets.includes(set)) {
    console.error(`Unknown set: "${set}". Available sets: ${allSets.join(', ')}`);
    process.exit(1);
  }

  const icons = require(path.join(SETS_DIR, set, 'index.json'));
  const setOutDir = path.join(OUT_DIR, set);

  fs.mkdirSync(setOutDir, {recursive: true});

  const barrelLines = ['// This file is autogenerated by "make react_icons", do not edit it.'];

  let count = 0;
  for (const icon of icons) {
    const svgPath = path.join(SETS_DIR, set, `${icon}.svg`);
    const svgContent = fs.readFileSync(svgPath, 'utf8');
    const tsx = svgToTsx(svgContent, icon);

    fs.writeFileSync(path.join(setOutDir, `${icon}.tsx`), tsx, 'utf8');

    const componentName = toComponentName(icon);
    barrelLines.push(`export {default as ${componentName}} from './${icon}';`);
    count++;
  }

  fs.writeFileSync(path.join(setOutDir, 'index.ts'), barrelLines.join('\n') + '\n', 'utf8');

  console.log(`${set}: ${count} icons`);
}

console.log('Done.');
